#!/usr/bin/env python3
"""Per-app share pages and link-preview cards.

For every public app box in index.html (article.showcase without the draft
class) this writes:
  <app>.html               the share page: Open Graph / Twitter tags for link
                           previews, then sends people to /#app-<app>
  assets/share/<app>.png   its 1200x630 card, rendered from
                           scripts/share/card.html by headless Chromium
plus assets/share/site.png, the card index.html's own tags point at.

The tagline comes from the store catalog (~/Code/store/gen/apps.json,
field `tagline`, owned by ~/Code/store); a public app without one is an
error. The name comes from .showcase-title and the color from that app's
--card-accent in style.css.

Usage: python3 -I scripts/share-cards.py [app ...]   (no args: all, plus site)
       just tool-share-cards [app ...]
"""

import html
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from urllib.parse import quote, urlencode

ROOT = Path(__file__).resolve().parent.parent
CATALOG = Path.home() / "Code/store/gen/apps.json"
CHROMIUM = "/Applications/Chromium.app/Contents/MacOS/Chromium"
CARD = ROOT / "scripts/share/card.html"
OUT = ROOT / "assets/share"
SITE = "https://bootlegcheeseburger.com"
MAX_BYTES = 400 * 1024

FAVICON = (
    "data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 64 64'"
    "%3E%3Ctext y='52' font-size='52'%3E%F0%9F%8D%94%3C/text%3E%3C/svg%3E"
)
SITE_CARD = {
    "icon": ROOT / "assets/blc-big.png",
    "name": "bootleg cheeseburger",
    "tag": "A small software studio. Tools for film post-production, pro audio, "
    "and other narrow weirdness.",
    "bg": "#faf7f2",
    "fg": "#1a1816",
    "mark": "0",
}


def die(msg):
    sys.exit(f"share-cards: {msg}")


def text_of(fragment):
    return html.unescape(re.sub(r"<[^>]+>", "", fragment)).strip()


def public_apps():
    """(id, name) for each non-draft app box in index.html."""
    page = (ROOT / "index.html").read_text()
    apps = []
    for m in re.finditer(r"<article\s([^>]*)>(.*?)</article>", page, re.S):
        attrs, body = m.groups()
        idm = re.search(r'\bid="app-([a-z0-9-]+)"', attrs)
        cls = re.search(r'\bclass="([^"]*)"', attrs)
        if not idm or not cls or "showcase" not in cls.group(1).split():
            continue
        if "draft" in cls.group(1).split():
            continue
        title = re.search(r'class="showcase-title">(.*?)</h2>', body, re.S)
        if not title:
            die(f"app-{idm.group(1)}: no .showcase-title")
        apps.append((idm.group(1), text_of(title.group(1))))
    return apps


def accents():
    css = (ROOT / "style.css").read_text()
    return dict(re.findall(r"\.showcase--([a-z0-9-]+)\s*\{[^}]*--card-accent:\s*(#[0-9a-fA-F]{3,8})", css))


def render(params, dest):
    """Screenshot the card with these params into dest (optimized PNG)."""
    query = urlencode({**params, "icon": params["icon"].as_uri()}, quote_via=quote)
    with tempfile.TemporaryDirectory() as tmp:
        raw = Path(tmp) / "card.png"
        subprocess.run(
            [
                CHROMIUM, "--headless", "--disable-gpu", "--hide-scrollbars",
                # Headless Chromium's viewport comes out shorter than the window,
                # so render in a taller window and crop the 1200x630 card.
                "--force-device-scale-factor=1", "--window-size=1200,900",
                "--virtual-time-budget=3000", "--allow-file-access-from-files",
                f"--user-data-dir={tmp}/profile", f"--screenshot={raw}",
                f"{CARD.as_uri()}?{query}",
            ],
            check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
        if not raw.exists():
            die(f"Chromium wrote no screenshot for {dest.name}")
        subprocess.run(
            ["magick", str(raw), "-crop", "1200x630+0+0", "+repage", "-strip", "-define", "png:compression-level=9", str(dest)],
            check=True,
        )
        if dest.stat().st_size > MAX_BYTES:
            # Flat colors and a few gradients: a 256-color palette holds up.
            subprocess.run(
                ["magick", str(raw), "-crop", "1200x630+0+0", "+repage", "-strip", "-dither", "None", "-colors", "256",
                 "-define", "png:compression-level=9", f"PNG8:{dest}"],
                check=True,
            )
    size = dest.stat().st_size
    print(f"{dest.relative_to(ROOT)}  {size // 1024} KB")
    if size > MAX_BYTES:
        print(f"  warning: over {MAX_BYTES // 1024} KB", file=sys.stderr)


def share_page(app, name, tagline):
    e = lambda s: html.escape(s, quote=True)
    url = f"{SITE}/{app}"
    title = f"{name} - {tagline}"
    return f"""<!doctype html>
<!-- Generated by scripts/share-cards.py; edit the script or the catalog, not this file. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width,initial-scale=1" />
    <title>{e(title)} | Bootleg Cheeseburger</title>
    <meta name="description" content="{e(tagline)}" />
    <link rel="canonical" href="{url}" />
    <link rel="icon" href="{FAVICON}" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="Bootleg Cheeseburger" />
    <meta property="og:title" content="{e(title)}" />
    <meta property="og:description" content="{e(tagline)}" />
    <meta property="og:url" content="{url}" />
    <meta property="og:image" content="{SITE}/assets/share/{app}.png" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta property="og:image:alt" content="{e(name)} app icon. {e(tagline)}" />
    <meta name="twitter:card" content="summary_large_image" />
    <script>
      location.replace("/#app-{app}");
    </script>
  </head>
  <body style="font-family: -apple-system, BlinkMacSystemFont, sans-serif; padding: 32px">
    <p><a href="/#app-{app}">{e(name)} - {e(tagline)}</a></p>
  </body>
</html>
"""


def main(wanted):
    if not CATALOG.is_file():
        die(f"no store catalog at {CATALOG} (clone ~/Code/store and run its gen)")
    catalog = json.loads(CATALOG.read_text())
    if not Path(CHROMIUM).exists():
        die(f"no Chromium at {CHROMIUM}")
    apps = public_apps()
    known = {a[0] for a in apps}
    for w in wanted:
        if w != "site" and w not in known:
            die(f"{w}: not a public app box in index.html")
    accent = accents()
    OUT.mkdir(parents=True, exist_ok=True)

    for app, name in apps:
        if wanted and app not in wanted:
            continue
        if app not in catalog:
            die(f"{app}: not in the store catalog {CATALOG}")
        tagline = (catalog[app].get("tagline") or "").strip()
        if not tagline:
            die(f"{app}: no tagline in the store catalog (~/Code/store/apps/{app}.toml)")
        if app not in accent:
            die(f"{app}: no --card-accent for .showcase--{app} in style.css")
        icon = ROOT / f"assets/{app}.png"
        if not icon.is_file():
            die(f"{app}: no {icon.relative_to(ROOT)}")
        render(
            {"icon": icon, "name": name, "tag": tagline, "bg": accent[app], "fg": "#ffffff", "mark": "1"},
            OUT / f"{app}.png",
        )
        (ROOT / f"{app}.html").write_text(share_page(app, name, tagline))
        print(f"{app}.html  {name} - {tagline}")

    if not wanted or "site" in wanted:
        render(SITE_CARD, OUT / "site.png")


if __name__ == "__main__":
    main(sys.argv[1:])
