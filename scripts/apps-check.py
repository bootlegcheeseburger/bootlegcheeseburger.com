#!/usr/bin/env python3
"""No app reaches the site unless the store catalog lists it and does not keep it secret.

An app is on the site when index.html names it, or when a share page or card
for it is in the tree. It fails when any of these names an app that is not in
<store>/gen/apps.json, or that eula-check's `hidden()` calls secret
(catalog `secret`, or status "unreleased" with no app box in index.html):
  1. an app box, `<article ... id="app-<app>" ...>`, draft or not;
  2. an in-page link `href="#app-<app>"` (the masthead Apps menu);
  3. an app icon `assets/<app>.png` in the Apps menu (`.nav-apps-menu`) or in
     an app box (other images, and assets/ subfolders, are not app icons);
  4. a share page `<app>.html` (one scripts/share-cards.py wrote, or any page
     named after a catalog app) or a card `assets/share/<app>.png` (site.png
     is the site's own card).
Reads only; never writes. Every problem is reported in one run; exit 1 on any.

Usage: python3 -I scripts/apps-check.py [--rev REV]
  --rev REV  check the site files as committed at REV (the pre-push hook passes
             each pushed commit) instead of the working tree.
Run by `just dev-check` and .githooks/pre-push. <store> is the store checkout
(STORE_REPO, see scripts/store_path.py).
"""
import importlib.util
import json
import os
import re
import subprocess
import sys

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REMOVE = "remove the box, its nav link, its icon and its card color"
ARTICLE = re.compile(r"<article\b([^>]*)>(.*?)</article>", re.S)
APP_ID = re.compile(r'\bid="app-([a-z0-9-]+)"')
APP_LINK = re.compile(r'\bhref="#app-([a-z0-9-]+)"')
MENU = re.compile(r'<div\b[^>]*\bclass="[^"]*(?<![\w-])nav-apps-menu(?![\w-])[^"]*"[^>]*>')
DIV = re.compile(r"<(/?)div\b", re.I)
ICON = re.compile(r"\bassets/([a-z0-9-]+)\.png\b")
SHARE_MARK = b"Generated by scripts/share-cards.py"


def load_eula_check():
    spec = importlib.util.spec_from_file_location("eula_check", os.path.join(SITE, "scripts", "eula-check.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def site_tree(rev):
    """Return (read(path) -> bytes | None, ls(dir) -> [names of files in it])
    over the working tree or a commit."""
    if rev is None:
        def read(path):
            try:
                with open(os.path.join(SITE, path), "rb") as f:
                    return f.read()
            except FileNotFoundError:
                return None

        def ls(d):
            p = os.path.join(SITE, d)
            try:
                return sorted(n for n in os.listdir(p) if os.path.isfile(os.path.join(p, n)))
            except FileNotFoundError:
                return []
        return read, ls

    def read(path):
        r = subprocess.run(["git", "-C", SITE, "cat-file", "blob", f"{rev}:{path}"], capture_output=True)
        return r.stdout if r.returncode == 0 else None

    def ls(d):
        r = subprocess.run(["git", "-C", SITE, "ls-tree", f"{rev}:{d}" if d else rev],
                           capture_output=True, text=True)
        if r.returncode != 0:
            return []
        # "<mode> <type> <sha>\t<name>"; files only, not subtrees
        return sorted(line.split("\t", 1)[1] for line in r.stdout.splitlines() if line.split()[1] == "blob")
    return read, ls


def block_end(page, pos):
    """End of the div whose open tag ends at pos (its matching </div>)."""
    depth = 1
    for m in DIV.finditer(page, pos):
        depth += -1 if m.group(1) else 1
        if depth == 0:
            return m.start()
    return len(page)


def main(argv):
    rev = None
    if argv[:1] == ["--rev"] and len(argv) == 2:
        rev = argv[1]
    elif argv:
        print(__doc__.strip().split("\n\n")[-1], file=sys.stderr)
        return 2

    # the store path (store_path.py) and "secret" come through eula-check, defined once
    eula_check = load_eula_check()
    hidden, store, catalog = eula_check.hidden, eula_check.STORE, eula_check.CATALOG
    if not os.path.isdir(store):
        print(f"apps-check: {eula_check.store_path.missing()} (the store catalog is the source)", file=sys.stderr)
        return 1
    try:
        with open(catalog, encoding="utf-8") as f:
            apps = json.load(f)
    except (OSError, ValueError) as e:
        print(f"apps-check: cannot read {catalog} ({e}); {eula_check.store_path.NEEDS}", file=sys.stderr)
        return 1

    read, ls = site_tree(rev)
    where = f" at {rev[:12]}" if rev else ""
    raw = read("index.html")
    if raw is None:
        print(f"apps-check: index.html is missing{where}", file=sys.stderr)
        return 1
    page = raw.decode("utf-8")

    def why(app):
        """None when the app may be on the site, else (what is wrong, the fix in index.html)."""
        entry = apps.get(app)
        if not isinstance(entry, dict):
            return f"{app} is not in {catalog}", f"add it to the store catalog, or {REMOVE}"
        if hidden(app, entry, raw):
            return f"{app} is secret (catalog `secret`, or unreleased with no app box)", REMOVE
        return None

    def line(pos):
        return page.count("\n", 0, pos) + 1

    found = []  # (pos, problem) in index.html, reported in page order
    named = set()

    def name(app, pos, what):
        named.add(app)
        bad = why(app)
        if bad:
            found.append((pos, f"index.html:{line(pos)}{where}: {what}: {bad[0]}: {bad[1]}"))

    scopes = []  # (start, end) of the Apps menu and every app box: where an assets/<x>.png is an app icon
    for a in ARTICLE.finditer(page):
        m = APP_ID.search(a.group(1))
        if not m:
            continue
        name(m.group(1), a.start(1) + m.start(), f"app box #app-{m.group(1)}")
        scopes.append((a.start(2), a.end(2)))
    for m in APP_LINK.finditer(page):
        name(m.group(1), m.start(), f"link to #app-{m.group(1)}")
    for m in MENU.finditer(page):
        scopes.append((m.end(), block_end(page, m.end())))
    for start, end in scopes:
        for m in ICON.finditer(page, start, end):
            name(m.group(1), m.start(), f"app icon assets/{m.group(1)}.png")
    problems = [p for _, p in sorted(found)]

    for f in ls(""):
        if not f.endswith(".html"):
            continue
        app = f[:-len(".html")]
        if app not in apps and SHARE_MARK not in (read(f) or b""):
            continue  # an ordinary page (contact.html, terms.html, ...), not a share page
        bad = why(app)
        if bad:
            problems.append(f"{f}{where}: a share page, but {bad[0]}: delete it and assets/share/{app}.png")
    for f in ls("assets/share"):
        if not f.endswith(".png") or f == "site.png":
            continue
        app = f[:-len(".png")]
        bad = why(app)
        if bad:
            problems.append(f"assets/share/{f}{where}: a share card, but {bad[0]}: delete it and {app}.html")

    for p in problems:
        print(f"apps-check: {p}", file=sys.stderr)
    if problems:
        return 1
    print(f"apps-check: ok{where} ({', '.join(sorted(named)) or 'no apps on the site'})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
